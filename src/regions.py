#: 纯展示顺序，对计算无影响）
REGION_ORDER: tuple[str, ...] = ("华北", "东北", "华东", "华中", "华南", "西南", "西北")


def region_of(city: str) -> str | None:
    """城市 → 大区；查不到返回 None（调用方必须显式处理，不许瞎猜）。"""
    prov = CITY_PROVINCE.get(city)
    if prov is None:
        return None
    return PROVINCE_REGION.get(prov)


def province_of(city: str) -> str | None:
    """城市 → 省份；查不到返回 None。"""
    return CITY_PROVINCE.get(city)
